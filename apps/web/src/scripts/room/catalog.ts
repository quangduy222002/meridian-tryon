/** Furniture and finish catalogues: plain data shared by the 2D plan, the 3D builder, the estimate and the AI. */

export interface FurnitureDef {
  name: string;
  /** Footprint in metres: w along the item's x, d along its z (front faces +z), h height. */
  w: number;
  d: number;
  h: number;
  /** Swatches for the main material; the first is the default. */
  colors: string[];
  /** Hint for naming rooms automatically. */
  room?: 'Living' | 'Bedroom' | 'Kitchen' | 'Bathroom' | 'Dining' | 'Study';
  /** Sits on the floor under other things (rugs): drawn first, never collides. */
  flat?: boolean;
  /** Catalogue section; pieces in one group are variants of each other (the inspector swaps between them). */
  group: string;
  /** Which part of a style's palette colours it: upholstery, cabinetry, timber, an accent, or fixed (sanitary ware). */
  role: 'fabric' | 'case' | 'wood' | 'accent' | 'fixed';
  /** Fixed to the ceiling or a wall instead of standing on the floor: never collides with floor furniture. */
  mount?: 'ceiling' | 'wall';
  /**
   * A light source: a downlight (spot, aimed down) or a lamp (point), at height y above the floor, with its output
   * relative to a 60 W-equivalent bulb.
   */
  light?: { kind: 'spot' | 'point'; y: number; power: number };
}

